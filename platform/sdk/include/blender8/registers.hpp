enum class Irq : std::uint8_t { timer0=0, timer1=1, tach=2, vblank=3, adc=4 };
[[nodiscard]] constexpr std::uint8_t mask(Irq source) noexcept {
    return static_cast<std::uint8_t>(1u << static_cast<unsigned>(source));
}
